    /// <summary>Default-Sprache: DE wenn Windows DE-sprachig ist, sonst EN.</summary>
    public static string DetectInitialLanguage()
    {
        var ui = System.Globalization.CultureInfo.CurrentUICulture.TwoLetterISOLanguageName;
        return ui == "de" ? "de" : "en";
    }

    public static string Get(string key, string language)
    {
        if (Strings.TryGetValue(language, out var dict) && dict.TryGetValue(key, out var v)) return v;
        if (Strings["en"].TryGetValue(key, out v)) return v;
        return key;
    }
